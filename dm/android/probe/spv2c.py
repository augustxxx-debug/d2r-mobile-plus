#!/usr/bin/env python3
"""SPIR-V → C 数组头文件。用法：spv2c.py <输出.h> <名字=文件.spv[:nocap=32,33]>…；nocap 去掉指定编号的 OpCapability（模拟 dmsh_vk 裁剪后的形状）。
SPIR-V -> C array header. Usage: spv2c.py <out.h> <name=file.spv[:nocap=32,33]>...; nocap removes the OpCapability words with the given numbers (the shape dmsh_vk's trimming leaves)."""
import struct, sys
out = open(sys.argv[1], 'w'); out.write('// generated by spv2c.py\n#include <stdint.h>\n')
for spec in sys.argv[2:]:
    name, _, rest = spec.partition('='); path, _, opt = rest.partition(':')
    w = list(struct.unpack('<%dI' % (len(open(path, 'rb').read()) // 4), open(path, 'rb').read()))
    if opt.startswith('nocap='):
        drop = {int(x) for x in opt[6:].split(',')}; i = 5; keep = w[:5]
        while i < len(w):
            n = w[i] >> 16; op = w[i] & 0xffff
            if not (op == 17 and n == 2 and w[i + 1] in drop): keep += w[i:i + n]
            i += n
        w = keep
    out.write('static const uint32_t %s[] = {%s};\nstatic const uint32_t %s_words = %d;\n' % (name, ','.join('0x%08x' % x for x in w), name, len(w)))
