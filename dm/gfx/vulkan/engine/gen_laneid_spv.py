#!/usr/bin/env python3
"""xbg_laneid_probe.comp → xbg_laneid_spv.h（用法：gen_laneid_spv.py <glslc>）。| Generates xbg_laneid_spv.h from xbg_laneid_probe.comp (usage: gen_laneid_spv.py <glslc>)."""
import os, struct, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__)); glslc = sys.argv[1]
spv = subprocess.run([glslc, '--target-env=vulkan1.1', '-O', '-o', '-', os.path.join(here, 'xbg_laneid_probe.comp')], check=True, stdout=subprocess.PIPE).stdout
w = struct.unpack('<%dI' % (len(spv) // 4), spv)
with open(os.path.join(here, 'xbg_laneid_spv.h'), 'w') as f:
    f.write('#pragma once\n#include <stdint.h>\n// Generated by gen_laneid_spv.py from xbg_laneid_probe.comp (glslc --target-env=vulkan1.1 -O); do not edit.\nstatic const uint32_t xbg_laneid_probe_cs[]={\n')
    for i in range(0, len(w), 8): f.write('    ' + ','.join('0x%x' % x for x in w[i:i + 8]) + ',\n')
    f.write('};\n')
print('words', len(w))
