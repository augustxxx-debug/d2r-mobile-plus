#!/bin/bash
# 版本号的唯一来源：iOS（dm/ios/run.sh）与 Mac（dm/tools/mac_app.sh）出包都从这里取，输出几行可 eval 的赋值：
#   DM_VERSION        给人看的版本号 x.y.z = HEAD 能到达的最高的 vX.Y.Z 标签（没有标签 = 0.0.0 并警告）。写进 CFBundleShortVersionString，App Store 只认三段数字。
#   DM_BUILD          构建号 = HEAD 的提交时间戳（秒）。同一分支上随提交递增、不随工作区干不干净变，浅克隆里也不变（提交数会变，所以不用）；
#                     比旧口径「月日时分」大，旧包查到新版本文件照样判「有新版」。写进 CFBundleVersion，新版本提示按它比大小。
#   DM_VERSION_LABEL  选角页、启动日志、诊断里给人看的一行：「1.0.0 · b346e40」；标签之后又有提交 =「1.0.0+28 · b346e40」；
#                     有未提交的代码改动再加「*」（本机着色器链生成的三份元数据不算，它们的版本单独记在构建输入 chain= 里）。
#   DM_VERSION_WARN   有话要说时的一句提醒（空 = 没有）。
# Single source of version numbers: both iOS (dm/ios/run.sh) and Mac (dm/tools/mac_app.sh) packaging take them from here; prints assignments to eval:
#   DM_VERSION        human version x.y.z = the highest vX.Y.Z tag reachable from HEAD (no tag = 0.0.0 with a warning). Goes into CFBundleShortVersionString; the App Store accepts three numbers only.
#   DM_BUILD          build number = HEAD's commit timestamp (seconds). Grows with commits on a branch, does not depend on whether the tree is clean, and does not change in a shallow clone
#                     (a commit count would, so it is not used); larger than the old month-day-hour-minute scheme, so old packages still see a new version file as newer. Goes into CFBundleVersion; the update notice compares it.
#   DM_VERSION_LABEL  the line people see on character select, in the boot log and in diagnostics: "1.0.0 · b346e40"; with commits after the tag = "1.0.0+28 · b346e40";
#                     a trailing "*" when there are uncommitted code changes (the three metadata files generated by the local shader chain do not count; their version is recorded as chain= in the build inputs).
#   DM_VERSION_WARN   one reminder line when there is something to say (empty = nothing).
set -u
cd "$(dirname "$0")" || exit 1
LOCAL_META='dm/gfx/nvn/dmsh_chain.h
dm/gfx/tools/dmsh_chain.lock
dm/gfx/nvn/c1_full.tsv'
warn=; ver=0.0.0; build=1; label=
if head=$(git rev-parse --short=7 HEAD 2>/dev/null); then
  tag=$(git tag --merged HEAD --list 'v*' 2>/dev/null | grep -E '^v[0-9]+\.[0-9]+\.[0-9]+$' | sort -V | tail -1)
  if [ -n "$tag" ]; then
    ver=${tag#v}; n=$(git rev-list --count "$tag..HEAD" 2>/dev/null || echo 0)
    label=$ver; [ "${n:-0}" -gt 0 ] && label="$ver+$n"
  else
    label=$ver; warn="没有 vX.Y.Z 标签：版本号按 0.0.0 出（git fetch --tags 取标签，或在发布提交上打 git tag v1.0.0）"
  fi
  build=$(git log -1 --format=%ct HEAD 2>/dev/null); build=${build:-1}
  code=$(git diff --name-only HEAD 2>/dev/null | grep -vxF "$LOCAL_META")
  label="$label · $head"; [ -n "$code" ] && label="$label*"
else
  label="$ver · 未知"; warn="读不到 git 提交：版本 0.0.0、构建号 1，这种包认不出源码"
fi
printf 'DM_VERSION=%q\nDM_BUILD=%q\nDM_VERSION_LABEL=%q\nDM_VERSION_WARN=%q\n' "$ver" "$build" "$label" "$warn"
