#!/bin/bash
# 版本号的唯一来源：iOS（dm/ios/run.sh）与 Mac（dm/tools/mac_app.sh）出包都从这里取，输出几行可 eval 的赋值：
#   DM_VERSION        给人看的版本号 x.y.z = HEAD 能到达的最高的 vX.Y.Z 标签（没有标签 = 0.0.0 并警告）。写进 CFBundleShortVersionString，App Store 只认三段数字。
#   DM_BUILD          构建号 = 沿提交历史严格递增的序号：每个提交取「自己的提交时间戳」与「各父提交的构建号 + 1」中较大的（四审 Q4-01）。
#                     历史上时间一直往前走时就等于提交时间戳；同一秒的父子提交、时钟回拨的提交也比所有祖先大。不随工作区干不干净变。
#                     浅克隆只按看得见的历史算，可能比完整克隆小（会警告），正式发布用完整克隆。写进 CFBundleVersion，新版本提示按它比大小。
#                     DM_BUILD_NUMBER=<正整数> 覆盖（出包脚本指定）；DM_BUILD_FLOOR=<上次发布的构建号> 时，构建号不大于它就拒绝（DM_VERSION_ERROR）。
#   DM_BUILD_SOURCE   构建号从哪来：history（按提交历史算）/ override（DM_BUILD_NUMBER）/ none（没有 git）。
#   DM_VERSION_LABEL  选角页、启动日志、诊断里给人看的一行：「1.0.0 · b346e40」；标签之后又有提交 =「1.0.0+28 · b346e40」；
#                     有未提交的代码改动再加「*」（本机着色器链生成的三份元数据不算，它们的版本单独记在构建输入 chain= 里）。
#   DM_VERSION_WARN   有话要说时的一句提醒（空 = 没有）。
#   DM_VERSION_ERROR  不能出包的原因（空 = 可以）。出包脚本 eval 之后必须检查它：eval 吞掉退出码。
# 参数：可选提交（缺省 HEAD），验包脚本用它算被测提交应有的构建号；不是 HEAD 时显示版本不看工作区。
# Single source of version numbers: both iOS (dm/ios/run.sh) and Mac (dm/tools/mac_app.sh) packaging take them from here; prints assignments to eval:
#   DM_VERSION        human version x.y.z = the highest vX.Y.Z tag reachable from HEAD (no tag = 0.0.0 with a warning). Goes into CFBundleShortVersionString; the App Store accepts three numbers only.
#   DM_BUILD          build number = a strictly increasing sequence along the commit history: each commit takes the larger of its own commit timestamp and every parent's build + 1 (fourth review Q4-01).
#                     While commit times move forward it equals the commit timestamp; a child committed in the same second as its parent, or after a clock went back, is still larger than every ancestor. Does not depend on whether the tree is clean.
#                     A shallow clone only counts the visible history and may come out smaller than a full clone (warned); release from a full clone. Goes into CFBundleVersion; the update notice compares it.
#                     DM_BUILD_NUMBER=<positive integer> overrides it (named by a packaging script); with DM_BUILD_FLOOR=<last released build>, a build not above it is refused (DM_VERSION_ERROR).
#   DM_BUILD_SOURCE   where the build number came from: history (computed from the commit history) / override (DM_BUILD_NUMBER) / none (no git).
#   DM_VERSION_LABEL  the line people see on character select, in the boot log and in diagnostics: "1.0.0 · b346e40"; with commits after the tag = "1.0.0+28 · b346e40";
#                     a trailing "*" when there are uncommitted code changes (the three metadata files generated by the local shader chain do not count; their version is recorded as chain= in the build inputs).
#   DM_VERSION_WARN   one reminder line when there is something to say (empty = nothing).
#   DM_VERSION_ERROR  why the package must not be built (empty = fine). Packaging scripts must check it after eval: eval swallows the exit status.
# Argument: an optional commit (default HEAD); the package check uses it for the build number the commit under test should carry. For a commit other than HEAD the label ignores the working tree.
set -u
cd "$(dirname "$0")" || exit 1
LOCAL_META='dm/gfx/nvn/dmsh_chain.h
dm/gfx/tools/dmsh_chain.lock
dm/gfx/nvn/c1_full.tsv'
REV=${1:-HEAD}
warn=; err=; ver=0.0.0; build=1; src=none; label=
if head=$(git rev-parse --short=7 "$REV^{commit}" 2>/dev/null); then
  shallow=$(git rev-parse --is-shallow-repository 2>/dev/null)
  tag=$(git tag --merged "$REV" --list 'v*' 2>/dev/null | grep -E '^v[0-9]+\.[0-9]+\.[0-9]+$' | sort -V | tail -1)
  if [ -n "$tag" ]; then
    ver=${tag#v}; n=$(git rev-list --count "$tag..$REV" 2>/dev/null || echo 0)
    label=$ver; [ "${n:-0}" -gt 0 ] && label="$ver+$n"
  elif [ "$shallow" = true ]; then
    label=$ver; warn="浅克隆缺历史：版本标签可能在看不见的历史里，版本号按 0.0.0 出（git fetch --unshallow --tags 取全历史与标签）"
  else
    label=$ver; warn="没有 vX.Y.Z 标签：版本号按 0.0.0 出（git fetch --tags 取标签，或在发布提交上打 git tag v1.0.0）"
  fi
  # 父提交先于子提交（--topo-order --reverse）；看不见的父提交（浅克隆边界）不参与 | parents come before children (--topo-order --reverse); parents beyond a shallow boundary are skipped
  build=$(git log --topo-order --reverse --format='%H %ct %P' "$REV" 2>/dev/null | awk '{ b = $2; for (i = 3; i <= NF; i++) if (($i in B) && B[$i] + 1 > b) b = B[$i] + 1; B[$1] = b; last = b } END { print last + 0 }')
  [ "${build:-0}" -gt 0 ] && src=history || build=1
  [ "$shallow" = true ] && warn="${warn:+${warn}；}浅克隆：构建号只按看得见的历史算，可能比完整克隆小，正式发布请用完整克隆"
  label="$label · $head"
  if [ "$REV" = HEAD ]; then code=$(git diff --name-only HEAD 2>/dev/null | grep -vxF "$LOCAL_META"); [ -n "$code" ] && label="$label*"; fi
else
  label="$ver · 未知"; warn="读不到 git 提交：版本 0.0.0、构建号 1，这种包认不出源码"
fi
if [ -n "${DM_BUILD_NUMBER:-}" ]; then
  case $DM_BUILD_NUMBER in (*[!0-9]*|0*) err="DM_BUILD_NUMBER「${DM_BUILD_NUMBER}」不是正整数";; (*) build=$DM_BUILD_NUMBER; src=override;; esac
fi
if [ -z "$err" ] && [ -n "${DM_BUILD_FLOOR:-}" ]; then
  case $DM_BUILD_FLOOR in
    (*[!0-9]*|'') err="DM_BUILD_FLOOR「${DM_BUILD_FLOOR}」不是整数";;
    (*) [ "$build" -le "$DM_BUILD_FLOOR" ] && err="构建号 ${build} 不大于上次发布的 ${DM_BUILD_FLOOR}：旧包会判成「没有新版本」，换一个更大的构建号（DM_BUILD_NUMBER）再出包";;
  esac
fi
printf 'DM_VERSION=%q\nDM_BUILD=%q\nDM_BUILD_SOURCE=%q\nDM_VERSION_LABEL=%q\nDM_VERSION_WARN=%q\nDM_VERSION_ERROR=%q\n' "$ver" "$build" "$src" "$label" "$warn" "$err"
